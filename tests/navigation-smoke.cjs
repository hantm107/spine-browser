const assert = require('node:assert/strict');
module.exports = async ({evaluate,until,check,wait,win}) => {
  win.setSize(1920,1080); await wait(100);
  await evaluate(`(async()=>{
    const file=allProjects[0];
    allProjects=Array.from({length:20},(_,i)=>({...file,id:'navigation-'+i,name:'Asset '+i}));
    searchInput.value='';workspace.category='all';favoritesOnly.checked=false;
    await selectProject(allProjects[0]);
    window.navigationOriginalSetup=setupPreview;window.navigationLoads=0;
    setupPreview=(...args)=>{window.navigationLoads++;return window.navigationOriginalSetup(...args);};
    projectList.focus();
  })()`);
  const press = key => evaluate(`document.activeElement.dispatchEvent(new KeyboardEvent('keydown',{key:${JSON.stringify(key)},bubbles:true,cancelable:true}))`);
  await press('ArrowRight'); await wait(70); await press('ArrowRight');
  await check('arrow navigation highlights immediately without loading intermediate files', `({selected:selectedProject.id,highlight:projectList.querySelector('.selected').dataset.id,loads:window.navigationLoads})`,r=>{assert.equal(r.selected,'navigation-0');assert.equal(r.highlight,'navigation-2');assert.equal(r.loads,0);});
  await wait(100);
  await check('preview debounce waits 200 ms after the last arrow press','window.navigationLoads',r=>assert.equal(r,0));
  await until('selectedProject.id === "navigation-2" && !!activePlayer?.skeleton');
  await check('rapid arrows load only the final selected file','window.navigationLoads',r=>assert.equal(r,1));
  await evaluate('selectProject(allProjects[0])');
  const below = await evaluate(`(()=>{const c=[...projectList.querySelectorAll('[data-id]')];return c.findIndex(x=>x.getBoundingClientRect().top>c[0].getBoundingClientRect().top+2);})()`);
  assert.ok(below>1,'Wide library has multiple columns');
  await press('ArrowDown');
  await check('Down moves to the same column in the next visual row',`projectList.querySelector('.selected').dataset.id`,r=>assert.equal(r,'navigation-'+below));
  await press('ArrowUp'); await wait(230);
  await evaluate('searchInput.focus()'); await press('ArrowRight'); await wait(230);
  await check('arrows in Search do not navigate the library','selectedProject.id',r=>assert.equal(r,'navigation-0'));
  await evaluate('projectList.focus()'); await press('ArrowRight');
  await evaluate('selectProject(allProjects[4])'); await wait(240);
  await check('explicit selection cancels a pending keyboard preview','selectedProject.id',r=>assert.equal(r,'navigation-4'));
  await until('!!activePlayer?.skeleton');
  await evaluate('activePlayer.paused=false;playerHost.querySelector("canvas").click()');
  await check('clicking the preview canvas pauses playback','activePlayer.paused',r=>assert.equal(r,true));
  await evaluate('playerHost.querySelector("canvas").click()');
  await check('clicking the preview canvas resumes playback','activePlayer.paused',r=>assert.equal(r,false));
  await evaluate('document.getElementById("playPauseBtn").click()');
  await check('playback control button still toggles pause','activePlayer.paused',r=>assert.equal(r,true));
  await evaluate('setupPreview=window.navigationOriginalSetup;delete window.navigationOriginalSetup;delete window.navigationLoads;projectList.focus()');
  win.setSize(1200,850);await wait(100);
};
